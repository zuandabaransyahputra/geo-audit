import { HIRE_URL, SITE_URL } from './constants';
import type { ActionItem } from './insights';
import { capMessage } from './score';
import type { Report, Status } from './types';

const ICON: Record<Status, string> = { pass: '✅', warn: '⚠️', fail: '❌', info: 'ℹ️' };

const VIS = { visible: '🟢 Visible', partly: '🟡 Partly', blocked: '🔴 Blocked', 'opted-out': '⚪ Opted out' } as const;

export function articleUrl(slug: string): string {
  return `${SITE_URL}/insights/${slug}`;
}

/** Points as shown to people: whole numbers, "<1" for tiny gains. */
export function points(n: number): string {
  return n < 1 ? '<1' : String(Math.round(n));
}

export function reportUrl(url: string, opts: { trainingOptOut?: boolean } = {}): string {
  return `${SITE_URL}/report?url=${encodeURIComponent(url)}${opts.trainingOptOut ? '&training=optout' : ''}`;
}

/** The whole report as GitHub-flavoured Markdown (for issues, PRs, docs). */
export function toMarkdown(report: Report): string {
  const out: string[] = [];
  out.push(`# GEO Audit: ${report.domain}`);
  out.push('');
  out.push(`**Score: ${report.score}/100 (grade ${report.grade})** · ${report.finalUrl} · ${report.fetchedAt.slice(0, 10)}`);
  out.push('');
  if (report.options.trainingOptOut) {
    out.push(`Training crawlers are treated as blocked on purpose${report.options.trainingOptOutSource === 'content-signal' ? ' (robots.txt: Content-Signal ai-train=no)' : ''}.`);
    out.push('');
  }
  if (report.cap) {
    out.push(`**${capMessage(report.cap, report.rawScore)}**`);
    out.push('');
  }
  out.push('| Category | Score | Weight |');
  out.push('| --- | ---: | ---: |');
  for (const c of report.categories) {
    out.push(c.tally ? `| ${c.label} | ${c.tally.passed} of ${c.tally.total} passed | not scored |` : `| ${c.label} | ${c.score} | ${Math.round(c.weight * 100)}% |`);
  }
  out.push('');

  const ins = report.insights;
  out.push(`> ${ins.summary}`);
  out.push('');

  out.push('## Who can see you');
  out.push('');
  out.push('| AI product | Status | Why |');
  out.push('| --- | --- | --- |');
  for (const v of ins.visibility) out.push(`| ${v.product} | ${VIS[v.status]} | ${v.reason.replace(/\|/g, '/')} |`);
  out.push('');

  const plan = ins.plan;
  const groups: [string, ActionItem[]][] = [
    ['Quick wins (minutes)', plan.quickWins],
    ['This week (hours)', plan.thisWeek],
    ['Bigger projects (days)', plan.bigger],
    ['Optional: agent readiness (not scored)', plan.optional],
  ];
  if (groups.some(([, items]) => items.length)) {
    out.push('## Action plan');
    out.push('');
    out.push(
      `Projected score: ${plan.current} now${plan.quickWins.length ? `, about ${plan.afterQuickWins} after the quick wins` : ''}, about ${plan.afterAll} after the full plan. Points and effort are estimates.`,
    );
    out.push('');
    for (const [label, items] of groups) {
      if (!items.length) continue;
      out.push(`### ${label}`);
      out.push('');
      items.forEach((f, i) =>
        out.push(
          `${i + 1}. **${f.title}**: ${f.summary} (${f.category === 'agent-readiness' ? 'optional' : `+${points(f.points)} pts${f.afterCap ? ' after the cap' : ''}`}, ${f.effortLabel}${f.note ? `; ${f.note.toLowerCase()}` : ''})${f.learnMore ? ` [Learn more](${articleUrl(f.learnMore)})` : ''}`,
        ),
      );
      out.push('');
    }
  }

  if (ins.strengths.length) {
    out.push('## Strengths');
    out.push('');
    for (const s of ins.strengths) out.push(`- ${s}`);
    out.push('');
  }

  for (const c of report.categories) {
    out.push(c.tally ? `## ${c.label} (${c.tally.passed} of ${c.tally.total} passed, not scored)` : `## ${c.label} (${c.score}/100)`);
    out.push('');
    for (const check of c.checks) {
      out.push(`### ${ICON[check.status]} ${check.title}${check.status === 'pass' && check.notes?.length ? ' (pass with notes)' : ''}`);
      out.push('');
      out.push(check.summary);
      out.push('');
      out.push(`*Why it matters:* ${check.why}${check.learnMore ? ` [Learn more](${articleUrl(check.learnMore)})` : ''}`);
      if (check.details?.length && check.status !== 'pass') {
        out.push('');
        for (const d of check.details) out.push(`- ${d}`);
      }
      if (check.notes?.length) {
        out.push('');
        for (const n of check.notes) out.push(`- Note: ${n}`);
      }
      if (check.fix && check.status !== 'pass') {
        out.push('');
        out.push(`**Fix:** ${check.fix.text}`);
        if (check.fix.snippet) {
          out.push('');
          out.push('```' + (check.fix.lang ?? ''));
          out.push(check.fix.snippet);
          out.push('```');
        }
      }
      out.push('');
    }
  }
  out.push('---');
  out.push('');
  out.push(`Generated by [GEO Audit](${reportUrl(report.url, { trainingOptOut: report.options.trainingOptOutSource === 'request' })}) v${report.toolVersion}. Need help fixing these? [Hire Zuanda](${HIRE_URL}).`);
  out.push('');
  return out.join('\n');
}
