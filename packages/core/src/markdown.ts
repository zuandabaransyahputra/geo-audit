import { HIRE_URL, SITE_URL } from './constants';
import { topFixes } from './score';
import type { Report, Status } from './types';

const ICON: Record<Status, string> = { pass: '✅', warn: '⚠️', fail: '❌', info: 'ℹ️' };

export function reportUrl(url: string): string {
  return `${SITE_URL}/report?url=${encodeURIComponent(url)}`;
}

/** The whole report as GitHub-flavoured Markdown (for issues, PRs, docs). */
export function toMarkdown(report: Report): string {
  const out: string[] = [];
  out.push(`# GEO Audit: ${report.domain}`);
  out.push('');
  out.push(`**Score: ${report.score}/100 (grade ${report.grade})** · ${report.finalUrl} · ${report.fetchedAt.slice(0, 10)}`);
  out.push('');
  out.push('| Category | Score | Weight |');
  out.push('| --- | ---: | ---: |');
  for (const c of report.categories) out.push(`| ${c.label} | ${c.score} | ${Math.round(c.weight * 100)}% |`);
  out.push('');

  const fixes = topFixes(report.categories, 5);
  if (fixes.length) {
    out.push('## Top fixes');
    out.push('');
    fixes.forEach((f, i) => out.push(`${i + 1}. **${f.title}**: ${f.summary} (+${Math.max(1, Math.round(f.impact))} pts)`));
    out.push('');
  }

  for (const c of report.categories) {
    out.push(`## ${c.label} (${c.score}/100)`);
    out.push('');
    for (const check of c.checks) {
      out.push(`### ${ICON[check.status]} ${check.title}`);
      out.push('');
      out.push(check.summary);
      out.push('');
      out.push(`*Why it matters:* ${check.why}`);
      if (check.details?.length && check.status !== 'pass') {
        out.push('');
        for (const d of check.details) out.push(`- ${d}`);
      }
      if (check.fix && check.status !== 'pass') {
        out.push('');
        out.push(`**Fix:** ${check.fix.text}`);
        if (check.fix.snippet) {
          out.push('');
          out.push('```' + (check.fix.lang ?? ''));
          out.push(check.fix.snippet);
          out.push('```');
        }
      }
      out.push('');
    }
  }
  out.push('---');
  out.push('');
  out.push(`Generated by [GEO Audit](${reportUrl(report.url)}) v${report.toolVersion}. Need help fixing these? [Hire Zuanda](${HIRE_URL}).`);
  out.push('');
  return out.join('\n');
}
